import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';

export async function verifySharedFavorites(page, frame, engine) {
  const read = () => page.evaluate(() => __PMM_FAVORITE_STORE__.read());
  await frame.evaluate(async () => { await (await __PMM_LOAD_WORLDBOOK_STITCH__()).open(); });
  const worldStar = page.locator('[data-wb-action="favorite"][data-wb-side="bottom"]').first();
  await page.locator('[data-wb-action="expand"][data-wb-side="bottom"]').first().click();
  await worldStar.click();
  await page.waitForFunction(() => __PMM_FAVORITE_STORE__.read().items.length === 1);
  assert.equal(await worldStar.getAttribute('aria-pressed'), 'true');
  assert.equal(await page.evaluate(() => fixtureWorldWrites), 0, 'Favoriting must not save the source book');
  await page.evaluate(() => { const side = __PMM_WORLDBOOK_STITCH_TEST3__.state.bottom; side.entries[0].content = 'unsaved world content'; side.dirty = true; });
  await page.locator('[data-wb-action="update-favorite"]').click();
  await page.waitForFunction(() => __PMM_FAVORITE_STORE__.read().items[0].content === 'unsaved world content');
  const favorite = (await read()).items[0];
  assert.equal(favorite.extra.pmmWorldbookFavorite.entry.depth, 7);
  // Switch directly from worldbook tools: the visible book becomes the top pane.
  await page.locator('.panel-btn[title="收藏"]').click();
  await page.waitForFunction(() => __PMM_WORLDBOOK_STITCH_TEST3__.state.favoriteMode);
  assert.equal(await page.evaluate(() => __PMM_WORLDBOOK_STITCH_TEST3__.state.top.entries[0].content), 'unsaved world content');
  await page.locator('[data-pmm-wb-panel="top"] [data-wb-kind="preset"]').click();
  const library = page.locator('.pm-panel-container > .preset-panel:not(.pmm-wb-inline-panel)');
  assert.equal(await library.locator('.pmm-favorite-kind').first().textContent(), '世界书');
  // Existing category operations and export/import must keep the metadata.
  await library.locator('[title="新建分类"]').click();
  await page.waitForFunction(() => __PMM_FAVORITE_STORE__.read().categories.length === 1);
  await page.evaluate(async () => { const api = __PMM_FAVORITE_STORE__, data = api.read(); await api.update(data.items[0].id, { categoryId: data.categories[0].id }); });
  const exportedPromise = page.waitForEvent('download');
  await library.locator('[title="导出"]').click();
  const exported = await exportedPromise;
  const backup = JSON.parse(await readFile(await exported.path(), 'utf8'));
  assert.equal(backup.data.items[0].extra.pmmWorldbookFavorite.entry.depth, 7);
  assert.equal(backup.data.items[0].categoryId, backup.data.categories[0].id);
  await page.evaluate(async () => { const api = __PMM_FAVORITE_STORE__; for (const item of api.read().items) await api.remove(item.id); });
  const chooserPromise = page.waitForEvent('filechooser');
  await library.locator('[title="导入"]').click();
  await (await chooserPromise).setFiles({ name: 'shared-favorites.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(backup)) });
  await page.waitForFunction(() => __PMM_FAVORITE_STORE__.read().items.length === 1);
  const restored = (await read()).items[0];
  assert.deepEqual(restored.extra, favorite.extra);
  assert.equal(restored.categoryId, (await read()).categories[0].id);

  assert.equal(await library.locator('[title="使用收藏"]').count(), 0);
  await page.waitForFunction(() => __PMM_WORLDBOOK_STITCH_TEST3__.state.favoriteMode);
  const drag = async (source, target, position = 'before') => {
    const dataTransfer = await page.evaluateHandle(() => new DataTransfer());
    await source.dispatchEvent('dragstart', { dataTransfer });
    await target.scrollIntoViewIfNeeded();
    const rect = await target.boundingBox();
    const point = { dataTransfer, clientX: rect.x + rect.width / 2, clientY: rect.y + rect.height * (position === 'before' ? .2 : .8) };
    await target.dispatchEvent('dragover', point);
    await target.dispatchEvent('drop', point);
    await source.dispatchEvent('dragend', { dataTransfer });
    await dataTransfer.dispose();
  };
  const card = library.locator('.prompt-card').first();
  const presetCards = page.locator('.pm-main-wrapper > .preset-panel:not(.pmm-wb-inline-panel) .prompt-card');
  const before = await page.evaluate(() => __PMM_WORLDBOOK_PRESET_DROP_BRIDGE__.snapshot().prompts);
  await drag(card, presetCards.nth(1));
  await page.waitForFunction(n => __PMM_WORLDBOOK_PRESET_DROP_BRIDGE__.snapshot().prompts.length === n + 1, before.length);
  const after = await page.evaluate(() => __PMM_WORLDBOOK_PRESET_DROP_BRIDGE__.snapshot().prompts);
  assert.deepEqual(after.filter((_, index) => index !== 1), before);
  assert.equal(after[1].content, 'unsaved world content'); assert.equal(after[1].role, 'system');
  assert.deepEqual(after[1].position, { type: 'relative' }); assert.ok(!after[1].extra?.pmmWorldbookFavorite);
  assert.equal((await read()).items.length, 1, 'Dragging copies the favorite');
  await page.locator('.pm-main-wrapper > .preset-panel:not(.pmm-wb-inline-panel) [data-wb-kind="world"]').click();
  const topWorld = page.locator('[data-pmm-wb-panel="top"]');
  await topWorld.locator('[data-wb-action="select-source"]').selectOption('Target');
  await page.waitForFunction(() => __PMM_WORLDBOOK_STITCH_TEST3__.state.top.entries[0]?.comment === '已有条目');
  assert.equal(await library.isVisible(), true, 'Favorite library remains visible alongside worldbook');
  await drag(card, topWorld.locator('.pmm-wb-entry').first());
  await page.waitForFunction(() => __PMM_WORLDBOOK_STITCH_TEST3__.state.top.entries.length === 2);
  const target = await page.evaluate(() => __PMM_WORLDBOOK_STITCH_TEST3__.state.top);
  assert.equal(target.entries[0].uid, 1); assert.equal(target.entries[1].uid, 0, 'Drop before exact target');
  assert.equal(target.entries[0].depth, 7); assert.equal(target.entries[0].probability, 63);
  assert.deepEqual(target.entries[0].custom, { x: ['keep'] });
  assert.equal(await page.evaluate(() => fixtureWorldWrites), 0, 'Drop only edits the draft');
  await page.evaluate(async () => { await __PMM_FAVORITE_STORE__.add({ name: 'Prompt favorite', content: 'prompt body', enabled: false, role: 'user', position: { type: 'relative' } }); });
  const promptCard = library.locator('.prompt-card').filter({ has: page.locator('.pmm-favorite-kind', { hasText: /^预设$/ }) });
  await drag(promptCard, topWorld.locator('.pmm-wb-entry').first(), 'after');
  await page.waitForFunction(() => __PMM_WORLDBOOK_STITCH_TEST3__.state.top.entries.length === 3);
  const mixed = await page.evaluate(() => __PMM_WORLDBOOK_STITCH_TEST3__.state.top.entries);
  assert.deepEqual(mixed.map(entry => entry.uid), [1, 2, 0]);
  assert.equal(mixed[1].disable, true); assert.deepEqual(mixed[1].key, []); assert.equal(mixed[1].position, 0);
  await topWorld.locator('[data-wb-kind="preset"]').click();
  assert.equal(await library.isVisible(), true);
  await page.locator('.pm-main-wrapper > .preset-panel:not(.pmm-wb-inline-panel) [data-wb-kind="world"]').click();
  await page.waitForFunction(() => document.querySelector('[data-pmm-wb-panel="top"]'));
  assert.equal(await page.evaluate(() => __PMM_WORLDBOOK_STITCH_TEST3__.state.top.entries.length), 3, 'Switching preset/world retains unsaved world additions');
  for (const width of [320, 390, 768]) {
    await page.setViewportSize({ width, height: 844 });
    assert.equal(await library.isVisible(), true); assert.equal(await topWorld.isVisible(), true);
  }
  await page.setViewportSize({ width:390, height:844 });
  if (process.env.PMM_BROWSER_ASSET_DIR) await page.screenshot({ path: process.env.PMM_BROWSER_ASSET_DIR + '/favorite-drag-' + engine + '.png' });
  await topWorld.locator('[data-wb-action="save"]').click();
  await page.waitForFunction(() => fixtureWorldWrites === 1);
  assert.deepEqual(await page.evaluate(() => Object.values(fixtureBooks.Target.entries).sort((a,b)=>a.displayIndex-b.displayIndex).map(e=>e.uid)), [1,2,0]);
  await page.locator('.panel-btn[title="收藏"]').click();
  const loadsBeforeFavorite = await page.evaluate(() => fixtureWorldLoads);
  await page.locator('.panel-btn[title="收藏"]').click();
  await page.waitForFunction(() => __PMM_WORLDBOOK_STITCH_TEST3__.state.favoriteMode);
  assert.equal(await page.evaluate(() => fixtureWorldLoads), loadsBeforeFavorite, 'Opening the library does not load worldbook contents');
  assert.equal(await page.evaluate(() => __PMM_WORLDBOOK_STITCH_TEST3__.state.topType), 'preset');
  await frame.evaluate(() => __PMM_LOAD_WORLDBOOK_STITCH__().then(api=>api.open()));
  await page.waitForFunction(() => __PMM_WORLDBOOK_STITCH_TEST3__.state.open && !__PMM_WORLDBOOK_STITCH_TEST3__.state.favoriteMode);
  await page.evaluate(() => __PMM_WORLDBOOK_STITCH_TEST3__.close());
  console.log(engine + ': shared upper view, exact preset/world drop positions, conversion, draft preservation, category/export/import and responsive panes passed');
}
