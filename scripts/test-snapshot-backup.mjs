import assert from 'node:assert/strict';
import { createBackup, validateBackup, planImport, commitImport, readStores, PRESET_KEY, WORLD_KEY } from '../dist/snapshot-backup-core.js';
const empty = () => ({ preset: { version: 1, snapshots: [], activeSnapshots: {}, manualSnapshots: {} }, world: { version: 1, snapshots: [], groups: [], defaults: [], owned: [], session: null } });
const sample = empty();
sample.preset.snapshots = [{ id: 'p', name: '常用', presetName: '测试预设', states: [{ id: 'entry', name: '条目', enabled: true, content: 'SECRET' }], characters: [{ key: 'a.png', name: '角色' }], chats: [{ key: 'chat', name: '聊天' }] },
  { id: 'default', name: '默认', presetName: '测试预设', isDefault: true, states: [] }];
sample.preset.activeSnapshots = { 测试预设: 'p' }; sample.preset.homeSnapshots = { 测试预设: 'p' };
sample.world.groups = [{ id: 'g', name: '通用组', books: ['书'], snapshot: 'w', enabled: true }];
sample.world.snapshots = [{ id: 'w', bundle: true, scope: 'group', owner: 'g', name: '方案', books: { 书: { 0: false, 1: true } } },
  { id: 'c', bundle: true, scope: 'character', owner: 'a.png', name: '角色方案', books: { 角色书: { 1: false } }, chat: 'chat' },
  { id: 'legacy', name: '旧快照', book: '旧书', scope: 'character', states: { 2: true }, characters: ['a.png'] }];
sample.world.defaults = [{ bundle: true, scope: 'group', owner: 'g', name: '默认', books: { 书: { 0: true } } }, { bundle: true, scope: 'character', owner: 'a.png', name: '默认', books: { 角色书: { 1: true } } }];
sample.world.owned = ['书']; sample.world.session = { before: { 书: { 0: true } } };
const backup = createBackup(sample);
assert.ok(!JSON.stringify(backup).includes('SECRET'));
assert.ok(!JSON.stringify(backup).includes('activeSnapshots'));
assert.ok(!JSON.stringify(backup).includes('session'));
assert.equal(backup.world.groups[0].enabled, false);
assert.deepEqual(validateBackup(JSON.parse(JSON.stringify(backup))), backup);
const plan = planImport(empty(), backup);
assert.deepEqual(plan.added, { preset: 2, world: 3, groups: 1, defaults: 2 });
assert.deepEqual(plan.next.preset.snapshots[0].characters, []);
assert.equal(plan.next.world.snapshots[1].chat, null);
assert.deepEqual(plan.next.world.snapshots[2].characters, []);
assert.equal(plan.next.world.groups[0].snapshot, 'w');
const bound = planImport(empty(), backup, true);
assert.equal(bound.next.preset.snapshots[0].chats[0].key, 'chat');
assert.equal(bound.next.world.snapshots[1].chat, 'chat');
assert.deepEqual(bound.next.world.snapshots[2].characters, ['a.png']);
assert.deepEqual(planImport(bound.next, backup, true).added, { preset: 0, world: 0, groups: 0, defaults: 0 });
const existing = structuredClone(sample);
existing.preset.snapshots[0].states[0].enabled = false;
assert.deepEqual(planImport(existing, backup, true).next, existing, 'Existing state, live journals and switches survive repeated import');
const conflict = empty(); conflict.world.groups.push({ id: 'another', name: '通用组', books: ['不同的书'], enabled: true });
const collision = planImport(conflict, backup);
assert.equal(collision.added.groups, 0); assert.equal(collision.added.world, 2); assert.equal(collision.added.defaults, 1);
const sameBinding = empty(); sameBinding.preset.snapshots.push({ ...sample.preset.snapshots[0], id: 'other', name: '别的方案' });
assert.deepEqual(planImport(sameBinding, backup, true).next.preset.snapshots.find(s => s.id === 'p').characters, []);
for (const corrupt of [{}, { ...backup, version: 100 }, { ...backup, world: { ...backup.world, groups: [] } }, { ...backup, preset: { snapshots: [{ ...backup.preset.snapshots[0], states: [{ id: 'x', enabled: 'false' }] }] } }]) assert.throws(() => validateBackup(corrupt));
const memory = new Map();
const storage = { getItem: k => memory.get(k) ?? null, setItem: (k, v) => memory.set(k, v), removeItem: k => memory.delete(k) };
commitImport(storage, bound);
assert.deepEqual(readStores(storage), bound.next);
const before = [...memory]; let fail = true;
const broken = { ...storage, setItem(k,v) { if (k === WORLD_KEY && fail) { fail = false; throw new Error('quota'); } storage.setItem(k,v); } };
assert.throws(() => commitImport(broken, plan), /原数据已保留/);
assert.deepEqual([...memory], before);
assert.ok(memory.has(PRESET_KEY));
console.log('Snapshot backup passed: round-trip, bindings, defaults, groups, legacy data, conflicts, runtime preservation, validation and rollback.');
